#!/usr/bin/env node
/**
 * Download Johnson Wax legacy images and emit scan/photograph data for pages.
 * Run from repo root: node scripts/build-johwax-assets.mjs
 */
import fs from "fs/promises";
import path from "path";
import { fileURLToPath } from "url";
import { createWriteStream } from "fs";
import { pipeline } from "stream/promises";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const LEGACY = "/tmp/johwax-legacy";
const BASE_URL = "http://nywf64.com";

const SKIP_IMAGE = /titlebar_background|getacro|adobereader|scrapbook|reader_get/i;

const PAGE_FILES = [
  ...Array.from({ length: 17 }, (_, i) =>
    path.join(LEGACY, `johwax${String(i + 1).padStart(2, "0")}.html`),
  ),
  path.join(LEGACY, "johwaxmap.shtml"),
];

function parseImages(html) {
  const re =
    /<img[^>]+src="([^"]+)"[^>]*(?:width="(\d+)"[^>]*height="(\d+)"|height="(\d+)"[^>]*width="(\d+)")[^>]*>/gi;
  const out = [];
  let m;
  while ((m = re.exec(html))) {
    const src = m[1];
    if (SKIP_IMAGE.test(src)) continue;
    const w = Number(m[2] || m[5]);
    const h = Number(m[3] || m[4]);
    out.push({ src, width: w || 300, height: h || 200 });
  }
  return out;
}

function localName(remotePath) {
  const base = path.basename(remotePath);
  const dir = path.basename(path.dirname(remotePath));
  if (dir && dir !== "Image" && !base.toLowerCase().includes(dir.toLowerCase())) {
    if (remotePath.includes("/pcards/")) return base;
    if (remotePath.includes("/arch/")) return `arch-${base}`;
    if (remotePath.includes("/mainliner/")) return `mainliner-${base}`;
    if (remotePath.includes("/photolab/")) return `photolab-${base}`;
  }
  return base;
}

async function download(url, dest) {
  await fs.mkdir(path.dirname(dest), { recursive: true });
  try {
    await fs.access(dest);
    return;
  } catch {
    /* fetch */
  }
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status} ${url}`);
  await pipeline(res.body, createWriteStream(dest));
}

async function downloadAll(jobs) {
  const concurrency = 24;
  let i = 0;
  async function worker() {
    while (i < jobs.length) {
      const job = jobs[i++];
      try {
        await download(job.url, job.dest);
      } catch (e) {
        console.error("FAIL", job.url, e.message);
      }
    }
  }
  await Promise.all(Array.from({ length: concurrency }, () => worker()));
}

function tsExport(name, value) {
  return `/* Generated by scripts/build-johwax-assets.mjs — do not edit by hand */\n\nexport const ${name} = ${JSON.stringify(value, null, 2)} as const;\n`;
}

function chunkRows(scans, columns) {
  const rows = [];
  for (let i = 0; i < scans.length; i += columns) {
    rows.push(scans.slice(i, i + columns));
  }
  return rows;
}

async function main() {
  const jobs = [];
  const pageImages = {};

  for (let n = 1; n <= 17; n++) {
    const slug = `johwax${String(n).padStart(2, "0")}`;
    const html = await fs.readFile(path.join(LEGACY, `${slug}.html`), "utf8");
    const imgs = parseImages(html);
    pageImages[slug] = [];
    for (const img of imgs) {
      const file = localName(img.src);
      const dest = path.join(ROOT, "public/images", slug, file);
      const url = `${BASE_URL}/${img.src.replace(/\\/g, "/")}`;
      jobs.push({ url, dest });
      pageImages[slug].push({
        file,
        width: img.width,
        height: img.height,
        publicPath: `/images/${slug}/${file}`,
      });
    }
  }

  // Map overlay
  jobs.push({
    url: `${BASE_URL}/Image/johwax/johwaxmap.gif`,
    dest: path.join(ROOT, "public/images/johwaxmap/johwaxmap.gif"),
  });

  console.log(`Downloading ${jobs.length} images…`);
  await downloadAll(jobs);

  // Scan pages: 07–14, 08–12, 15 filmstrip tiles (exclude intro johwax35 handled in page)
  for (const slug of [
    "johwax07",
    "johwax08",
    "johwax09",
    "johwax10",
    "johwax11",
    "johwax12",
    "johwax13",
    "johwax14",
  ]) {
    const scans = pageImages[slug].map(({ publicPath, width, height, file }) => ({
      src: publicPath,
      width,
      height,
      alt: file,
    }));
    const constName = slug.toUpperCase().replace("JOHWAX", "JOHWAX_") + "_SCANS";
    await fs.writeFile(
      path.join(ROOT, "src/data", `${slug}Scans.ts`),
      tsExport(constName, scans),
    );
  }

  // johwax06 gallery — flat scan list
  {
    const scans = pageImages.johwax06.map(({ publicPath, width, height, file }) => ({
      src: publicPath,
      width,
      height,
      alt: file,
    }));
    await fs.writeFile(
      path.join(ROOT, "src/data/johwax06Scans.ts"),
      tsExport("JOHWAX_06_SCANS", scans),
    );
  }

  // johwax15 — jw00/jw01… sequences (exclude johwax35 for intro)
  {
    const scans = pageImages.johwax15
      .filter((p) => !p.file.toLowerCase().includes("johwax35"))
      .map(({ publicPath, width, height, file }) => ({
        src: publicPath,
        width,
        height,
        alt: file,
      }));
    await fs.writeFile(
      path.join(ROOT, "src/data/johwax15Scans.ts"),
      tsExport("JOHWAX_15_SCANS", scans),
    );
  }

  // johwax05 photograph sections (simple parser)
  const html05 = await fs.readFile(path.join(LEGACY, "johwax05.html"), "utf8");
  const sections = [];
  const sectionRe =
    /<b><font face="Arial[^"]*">(Commercial Photographs|Fairgoer Photographs)<\/font><\/b>/gi;
  const parts = html05.split(sectionRe);
  for (let i = 1; i < parts.length; i += 2) {
    const heading = parts[i];
    const body = parts[i + 1] || "";
    const photos = [];
    const cardRe =
      /<b><font face="Arial[^"]*" size="2"><b>([^<]+)<\/b><\/font>[\s\S]*?SOURCE:[^<]*<\/font>([\s\S]*?)<\/dt>[\s\S]*?<img src="([^"]+)" width="(\d+)" height="(\d+)"/gi;
    let cm;
    while ((cm = cardRe.exec(body))) {
      const title = cm[1].trim();
      let sourceRaw = cm[2].replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim();
      if (!sourceRaw.startsWith("SOURCE:")) sourceRaw = `SOURCE: ${sourceRaw}`;
      const remote = cm[3];
      const file = localName(remote);
      photos.push({
        image: {
          src: `/images/johwax05/${file}`,
          width: Number(cm[4]),
          height: Number(cm[5]),
        },
        title,
        source: sourceRaw,
      });
    }
    if (photos.length) sections.push({ heading, photos });
  }

  await fs.writeFile(
    path.join(ROOT, "src/data/johwax05Sections.ts"),
    `/* Generated by scripts/build-johwax-assets.mjs */
import type { PhotographSection } from "@/components/PhotographsPage";

export const JOHWAX_05_SECTIONS: PhotographSection[] = ${JSON.stringify(sections, null, 2)};
`,
  );

  const counts = Object.fromEntries(
    Object.entries(pageImages).map(([k, v]) => [k, v.length]),
  );
  console.log("Image counts per page:", counts);
  console.log("johwax05 sections:", sections.map((s) => `${s.heading}: ${s.photos.length}`));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
